void emit_port_registry_metadata(std::ostringstream& oss, const std::vector<ComponentPorts>& all_components) {
    for (const auto& comp : all_components) {
        oss << "constexpr const char* " << comp.classname << "_PORTS[] = {\n";
        for (size_t i = 0; i < comp.ports.size(); ++i) {
            oss << "    \"" << comp.ports[i].name << "\"";
            if (i < comp.ports.size() - 1) {
                oss << ",\n";
            } else {
                oss << "\n";
            }
        }
        oss << "};\n";
    }
    oss << "\n";

    oss << "#include \"../../../../blueprint_v2/interface/direction.h\"\n\n";
    for (const auto& comp : all_components) {
        oss << "constexpr bp2::Direction " << comp.classname << "_PORT_DIRECTIONS[] = {\n";
        for (size_t i = 0; i < comp.ports.size(); ++i) {
            const char* dir_name = "Output";
            if (comp.ports[i].direction == bp2::Direction::Input) {
                dir_name = "Input";
            } else if (comp.ports[i].direction == bp2::Direction::InOut) {
                dir_name = "InOut";
            }
            oss << "    bp2::Direction::" << dir_name;
            if (i < comp.ports.size() - 1) {
                oss << ",\n";
            } else {
                oss << "\n";
            }
        }
        oss << "};\n";

        oss << "constexpr uint8_t " << comp.classname << "_PORT_DOMAINS[] = {\n";
        for (size_t i = 0; i < comp.ports.size(); ++i) {
            oss << "    " << static_cast<int>(static_cast<uint8_t>(comp.ports[i].domain));
            if (i < comp.ports.size() - 1) {
                oss << ",\n";
            } else {
                oss << "\n";
            }
        }
        oss << "};\n";

        oss << "constexpr bool " << comp.classname << "_PORT_SOURCE_WRITER[] = {\n";
        for (size_t i = 0; i < comp.ports.size(); ++i) {
            oss << "    " << (comp.ports[i].source_writer ? "true" : "false");
            if (i < comp.ports.size() - 1) {
                oss << ",\n";
            } else {
                oss << "\n";
            }
        }
        oss << "};\n";

        oss << "constexpr bool " << comp.classname << "_SCHEDULER_SOURCE = "
            << (comp.scheduler_source ? "true" : "false") << ";\n\n";
        oss << "constexpr bool " << comp.classname << "_SOLVER_OWNED_ELECTRICAL = "
            << (comp.solver_owned_electrical ? "true" : "false") << ";\n\n";
    }
}

void emit_port_registry_lookups(
    std::ostringstream& oss,
    const std::vector<ComponentPorts>& all_components,
    const std::set<std::string>& all_port_names
) {
    oss << "inline std::optional<PortNames> string_to_port_name(const std::string& name) {\n";
    oss << "    static const std::unordered_map<std::string, PortNames> map = {\n";
    for (const auto& port_name : all_port_names) {
        oss << "        {\"" << port_name << "\", PortNames::" << port_name << "},\n";
    }
    oss << "    };\n";
    oss << "    auto it = map.find(name);\n";
    oss << "    if (it != map.end()) return it->second;\n";
    oss << "    return std::nullopt;\n";
    oss << "}\n\n";

    oss << "inline std::vector<std::string> get_component_ports(const std::string& classname) {\n";
    oss << "    static const std::unordered_map<std::string, std::vector<std::string>> registry = {\n";
    for (const auto& comp : all_components) {
        oss << "        {\"" << comp.classname << "\", {";
        for (size_t i = 0; i < comp.ports.size(); ++i) {
            oss << "\"" << comp.ports[i].name << "\"";
            if (i < comp.ports.size() - 1) {
                oss << ", ";
            }
        }
        oss << "}},\n";
    }
    oss << "    };\n";
    oss << "    auto it = registry.find(classname);\n";
    oss << "    if (it != registry.end()) return it->second;\n";
    oss << "    return {};\n";
    oss << "}\n\n";

    oss << "inline bool has_component_metadata(const std::string& classname) {\n";
    oss << "    static const std::unordered_set<std::string> known = {\n";
    for (const auto& comp : all_components) {
        oss << "        \"" << comp.classname << "\",\n";
    }
    oss << "    };\n";
    oss << "    return known.count(classname) > 0;\n";
    oss << "}\n\n";

    oss << "inline void require_component_metadata(const std::string& classname, const char* helper_name) {\n";
    oss << "    if (!has_component_metadata(classname)) {\n";
    oss << "        throw std::runtime_error(std::string(\"Unknown component metadata class in \") + helper_name + \": \" + classname);\n";
    oss << "    }\n";
    oss << "}\n\n";

    oss << "inline bool is_scheduler_source_component(const std::string& classname) {\n";
    oss << "    require_component_metadata(classname, \"is_scheduler_source_component\");\n";
    oss << "    static const std::unordered_map<std::string, bool> registry = {\n";
    for (const auto& comp : all_components) {
        oss << "        {\"" << comp.classname << "\", " << (comp.scheduler_source ? "true" : "false") << "},\n";
    }
    oss << "    };\n";
    oss << "    auto it = registry.find(classname);\n";
    oss << "    if (it == registry.end()) throw std::runtime_error(\"Missing scheduler-source metadata entry for known class: \" + classname);\n";
    oss << "    return it->second;\n";
    oss << "}\n\n";

    oss << "inline bool is_solver_owned_electrical_component(const std::string& classname) {\n";
    oss << "    require_component_metadata(classname, \"is_solver_owned_electrical_component\");\n";
    oss << "    static const std::unordered_map<std::string, bool> registry = {\n";
    for (const auto& comp : all_components) {
        oss << "        {\"" << comp.classname << "\", " << (comp.solver_owned_electrical ? "true" : "false") << "},\n";
    }
    oss << "    };\n";
    oss << "    auto it = registry.find(classname);\n";
    oss << "    if (it == registry.end()) throw std::runtime_error(\"Missing solver-owned metadata entry for known class: \" + classname);\n";
    oss << "    return it->second;\n";
    oss << "}\n\n";

    oss << "inline bool requires_solver_role_component(const std::string& classname) {\n";
    oss << "    require_component_metadata(classname, \"requires_solver_role_component\");\n";
    oss << "    static const std::unordered_map<std::string, bool> registry = {\n";
    for (const auto& comp : all_components) {
        oss << "        {\"" << comp.classname << "\", " << (comp.has_solver_role ? "true" : "false") << "},\n";
    }
    oss << "    };\n";
    oss << "    auto it = registry.find(classname);\n";
    oss << "    if (it == registry.end()) throw std::runtime_error(\"Missing solver-role metadata entry for known class: \" + classname);\n";
    oss << "    return it->second;\n";
    oss << "}\n\n";

    oss << "inline std::vector<std::string> get_output_ports(const std::string& classname) {\n";
    oss << "    require_component_metadata(classname, \"get_output_ports\");\n";
    oss << "    std::vector<std::string> result;\n";
    for (const auto& comp : all_components) {
        oss << "    if (classname == \"" << comp.classname << "\") {\n";
        oss << "        for (size_t i = 0; i < " << comp.classname << "_PORT_COUNT; ++i) {\n";
        oss << "            if (" << comp.classname << "_PORT_DIRECTIONS[i] == bp2::Direction::Output || "
            << comp.classname << "_PORT_DIRECTIONS[i] == bp2::Direction::InOut) result.push_back(" << comp.classname << "_PORTS[i]);\n";
        oss << "        }\n";
        oss << "        return result;\n";
        oss << "    }\n";
    }
    oss << "    throw std::runtime_error(\"Missing output-port metadata entry for known class: \" + classname);\n";
    oss << "}\n\n";

    oss << "inline std::vector<std::string> get_source_writer_ports(const std::string& classname, uint8_t domain_mask) {\n";
    oss << "    require_component_metadata(classname, \"get_source_writer_ports\");\n";
    oss << "    std::vector<std::string> result;\n";
    for (const auto& comp : all_components) {
        oss << "    if (classname == \"" << comp.classname << "\") {\n";
        oss << "        for (size_t i = 0; i < " << comp.classname << "_PORT_COUNT; ++i) {\n";
        oss << "            if (" << comp.classname << "_PORT_SOURCE_WRITER[i] && ((" << comp.classname << "_PORT_DOMAINS[i] & domain_mask) != 0)) result.push_back(" << comp.classname << "_PORTS[i]);\n";
        oss << "        }\n";
        oss << "        return result;\n";
        oss << "    }\n";
    }
    oss << "    throw std::runtime_error(\"Missing source-writer metadata entry for known class: \" + classname);\n";
    oss << "}\n\n";
}

void emit_port_registry_variant(std::ostringstream& oss, const std::vector<ComponentPorts>& all_components) {
    oss << "using ComponentVariant = std::variant<\n";
    for (size_t i = 0; i < all_components.size(); ++i) {
        oss << "    " << all_components[i].classname << "<JitProvider>";
        if (i < all_components.size() - 1) {
            oss << ",\n";
        } else {
            oss << "\n";
        }
    }
    oss << ">;\n\n";

    oss << "static_assert(\n";
    oss << "    std::variant_size_v<ComponentVariant> == static_cast<size_t>(ComponentType::_COUNT),\n";
    oss << "    \"ComponentType enum and ComponentVariant are out of sync — regenerate port_registry.h\"\n";
    oss << ");\n\n";
}

void generate_port_names_header(const std::string& output_path, const std::set<std::string>& all_port_names) {
    std::string dir = output_path;
    auto slash = dir.find_last_of("/\\");
    if (slash != std::string::npos) {
        dir = dir.substr(0, slash + 1);
    } else {
        dir.clear();
    }
    std::string port_names_path = dir + "port_names.h";

    std::ostringstream pn;
    pn << "// Auto-generated by codegen from library/*.blueprint\n";
    pn << "// DO NOT EDIT - changes will be overwritten\n\n";
    pn << "#pragma once\n\n";
    pn << "#include <cstdint>\n\n";
    pn << "enum class PortNames : uint32_t {\n";
    for (const auto& port_name : all_port_names) {
        pn << "    " << port_name << ",\n";
    }
    pn << "    _COUNT\n";
    pn << "};\n";

    std::ofstream pn_out(port_names_path);
    if (pn_out.is_open()) {
        pn_out << pn.str();
        pn_out.close();
    }
}

