/// Convert a default value string to a valid C++ float literal.
static std::string float_literal(const std::string& v) {
    if (v.empty()) return "0.0f";
    if (v.find('.') != std::string::npos || v.find('e') != std::string::npos || v.find('E') != std::string::npos) {
        return v + "f";
    }
    return v + ".0f";
}

/// Emit a single param assignment line with given indentation.
/// Returns true if code was emitted (false for table params, handled separately).
static bool emit_param_assignment(std::ostringstream& oss, const CodegenParam& p, const char* indent = "    ") {
    const std::string& def = p.default_value;

    switch (p.type) {
    case ParamSchemaType::Float:
        oss << indent << "comp." << p.field << " = param_reader.consume_float_optional(\""
            << p.name << "\", " << float_literal(def) << ");\n";
        return true;
    case ParamSchemaType::Int:
        oss << indent << "comp." << p.field << " = static_cast<int>(param_reader.consume_float_optional(\""
            << p.name << "\", " << float_literal(def) << "));\n";
        return true;
    case ParamSchemaType::Bool:
        oss << indent << "comp." << p.field << " = param_reader.consume_bool_optional(\""
            << p.name << "\", " << (def == "true" || def == "1" ? "true" : "false") << ");\n";
        return true;
    case ParamSchemaType::String:
        oss << indent << "comp." << p.field << " = param_reader.consume_string_optional(\""
            << p.name << "\", \"" << p.default_value << "\");\n";
        return true;
    case ParamSchemaType::Table:
        return false;
    }
    return false;
}

/// Determine scheduler role string for the generic template.
static const char* scheduler_role_for(const ComponentPorts& comp) {
    switch (comp.scheduler_role_kind) {
        case SchedulerRoleKind::None:    return "None";
        case SchedulerRoleKind::Source:  return "Source";
        case SchedulerRoleKind::Consumer: return "Consumer";
    }
    return "Consumer";
}

/// Emit the scheduler registration line derived from component metadata.
/// Uses the same logic as build_generic's if constexpr dispatch.
static void emit_scheduler_add(std::ostringstream& oss, const ComponentPorts& comp, const char* indent = "    ") {
    const std::string& cn = comp.classname;
    switch (comp.scheduler_role_kind) {
        case SchedulerRoleKind::None:
            // No scheduler registration — managed by subsolver
            break;
        case SchedulerRoleKind::Source:
            oss << indent << "result.scheduler.add_source(&std::get<" << cn << "<JitProvider>>(result.devices[dev.name]));\n";
            break;
        case SchedulerRoleKind::Consumer:
            oss << indent << "result.scheduler.add_consumer(&std::get<" << cn << "<JitProvider>>(result.devices[dev.name]));\n";
            break;
    }
}

/// Does this component require a special (non-generic) builder?
/// Special cases: LUT (table arena allocation), RefNode (fixed signal registration).
static bool needs_special_builder(const ComponentPorts& comp) {
    if (comp.solver_role_kind == SolverRoleKind::FixedVoltageNode) return true;
    for (const auto& p : comp.params) {
        if (p.type == ParamSchemaType::Table) return true;
    }
    return false;
}

/// Emit the consume_params() overload for a single component.
/// Overloaded on CompType — the generic build template calls the right one via ADL.
static void emit_consume_params_overload(std::ostringstream& oss, const ComponentPorts& comp) {
    const std::string& cn = comp.classname;
    oss << "static void consume_params(" << cn << "<JitProvider>& comp, ParamReader& param_reader) {\n";
    bool emitted = false;
    for (const auto& p : comp.params) {
        if (p.type != ParamSchemaType::Table) {
            emit_param_assignment(oss, p, "    ");
            emitted = true;
        }
    }
    if (!emitted) {
        oss << "    (void)comp; (void)param_reader;  // no params\n";
    }
    oss << "}\n\n";
}

/// Emit the generic build template — shared construct→finish flow for all vanilla components.
static void emit_build_generic_template(std::ostringstream& oss) {
    oss << R"(/// Generic builder template: construct → consume_params → build_finish.
/// Handles 69/71 components — only LUT (arena) and RefNode (fixed signals) need custom builders.
template <typename CompType, SchedulerRoleKind Role>
static void build_generic(BuildResult& result, const SolverDevice& dev, ParamReader& param_reader) {
     CompType comp;
     consume_params(comp, param_reader);
     if constexpr (requires { comp.pre_load(); }) { comp.pre_load(); }
     setup_component_ports(result, dev, comp);
     param_reader.validate_all_consumed();
     result.devices[dev.name] = std::move(comp);
     if constexpr (Role == SchedulerRoleKind::Consumer)
         result.scheduler.add_consumer(&std::get<CompType>(result.devices[dev.name]));
     else if constexpr (Role == SchedulerRoleKind::Source)
         result.scheduler.add_source(&std::get<CompType>(result.devices[dev.name]));
 }

)";

}

/// Emit the special builder for LUT — arena allocation for table data.
static void emit_build_LUT(std::ostringstream& oss, const ComponentPorts& comp) {
    const std::string& cn = comp.classname;
    oss << "/// Special builder: " << cn << " — table arena allocation before pre_load.\n";
    oss << "static void build_" << cn << "(BuildResult& result, const SolverDevice& dev, ParamReader& param_reader) {\n";
    oss << "    " << cn << "<JitProvider> comp;\n";
    oss << "    consume_params(comp, param_reader);\n";
    // Emit table arena block (function-level indentation)
    for (const auto& p : comp.params) {
        if (p.type != ParamSchemaType::Table) continue;
        oss << "    if (auto it = dev.params.find(\"" << p.name << "\"); it != dev.params.end()) {\n";
        oss << "        const std::string " << p.name << "_str = param_reader.consume_string_optional(\""
            << p.name << "\", \"\");\n";
        oss << "        std::vector<float> keys, vals;\n";
        oss << "        if (" << cn << "<JitProvider>::parse_table(" << p.name << "_str, keys, vals)) {\n";
        oss << "            comp." << p.arena_field_offset << " = static_cast<uint32_t>(result.lut_keys.size());\n";
        oss << "            comp." << p.arena_field_size << " = static_cast<uint16_t>(keys.size());\n";
        oss << "            result.lut_keys.insert(result.lut_keys.end(), keys.begin(), keys.end());\n";
        oss << "            result.lut_values.insert(result.lut_values.end(), vals.begin(), vals.end());\n";
        oss << "        }\n";
        oss << "    }\n";
    }
    oss << "    setup_component_ports(result, dev, comp);\n";
    oss << "    param_reader.validate_all_consumed();\n";
    oss << "    result.devices[dev.name] = std::move(comp);\n";
    emit_scheduler_add(oss, comp);
    oss << "}\n\n";
}

/// Emit the special builder for RefNode — fixed signal registration after build.
static void emit_build_RefNode(std::ostringstream& oss, const ComponentPorts& comp) {
    const std::string& cn = comp.classname;
    oss << "/// Special builder: " << cn << " — fixed signal registration after scheduler add.\n";
    oss << "static void build_" << cn << "(BuildResult& result, const SolverDevice& dev, ParamReader& param_reader) {\n";
    oss << "    " << cn << "<JitProvider> comp;\n";
    oss << "    consume_params(comp, param_reader);\n";
    oss << "    setup_component_ports(result, dev, comp);\n";
    oss << "    param_reader.validate_all_consumed();\n";
    oss << "    result.devices[dev.name] = std::move(comp);\n";
    emit_scheduler_add(oss, comp);
    oss << "    {\n";
    oss << "        const std::string key = dev.name + \".v\";\n";
    oss << "        const core::InternedId iid = result.signal_key_interner.lookup(key);\n";
    oss << "        auto it_sig = result.port_to_signal.find(iid);\n";
    oss << "        if (it_sig != result.port_to_signal.end()) {\n";
    oss << "            result.fixed_signals.push_back(it_sig->second);\n";
    oss << "        }\n";
    oss << "    }\n";
    oss << "}\n\n";
}

/// Emit the dispatch table and main build function.
static void emit_dispatch_table_and_main(std::ostringstream& oss, const std::vector<ComponentPorts>& all_components) {
    oss << R"(/// Dispatch table — one entry per ComponentKind, indexed by enum value.
using BuildFn = void(*)(BuildResult&, const SolverDevice&, ParamReader&);

/// Sentinel for unsupported ComponentKind values (Unknown).
/// Should never be called — guarded by has_component_metadata() check in the main loop.
[[noreturn]] static void build_unsupported(BuildResult&, const SolverDevice& dev, ParamReader&) {
    throw std::runtime_error("No factory handler for component '" + dev.classname + "'");
}

static const BuildFn BUILD_TABLE[] = {
)";

    for (const auto& comp : all_components) {
        const std::string& cn = comp.classname;
        if (comp.solver_role_kind == SolverRoleKind::FixedVoltageNode) {
            oss << "    build_" << cn << ",  // " << cn << " (special: fixed signals)\n";
        } else if (needs_special_builder(comp)) {
            oss << "    build_" << cn << ",  // " << cn << " (special: table arena)\n";
        } else {
            oss << "    build_generic<" << cn << "<JitProvider>, SchedulerRoleKind::" << scheduler_role_for(comp) << ">,  // " << cn << "\n";
        }
    }

    // Sentinel for Unknown — the last real enum value before _COUNT.
    oss << "    build_unsupported,  // Unknown (sentinel — guarded by has_component_metadata)\n";
    oss << "};\n\n";

    // Emit a static_assert that table size matches ComponentKind count
    oss << "static_assert(sizeof(BUILD_TABLE) / sizeof(BUILD_TABLE[0]) == static_cast<size_t>(ComponentKind::_COUNT),\n";
    oss << "    \"BUILD_TABLE size must match ComponentKind count\");\n\n";

    oss << R"(void build_and_register_components(
    BuildResult& result,
    const std::vector<SolverDevice>& devices)
{
    result.devices.reserve(devices.size());  // Prevent rehash invalidating scheduler pointers

    std::vector<std::string> consumer_device_names;

    for (const auto& dev : devices) {
        if (!has_component_metadata(dev.kind)) {
            throw std::runtime_error("Missing generated port metadata for component class '" + dev.classname + "'");
        }

        if (dev.scheduler_role_kind == SchedulerRoleKind::Consumer) {
            consumer_device_names.push_back(dev.name);
        }

        ParamReader param_reader(dev.params, dev);

        BUILD_TABLE[static_cast<size_t>(dev.kind)](result, dev, param_reader);
    }

    // Post-registration pass: Deduplicate fixed signals
    std::sort(result.fixed_signals.begin(), result.fixed_signals.end());
    result.fixed_signals.erase(
        std::unique(result.fixed_signals.begin(), result.fixed_signals.end()),
        result.fixed_signals.end());

    // Sentinel is a fixed signal: always allocated at the end, never changes
    result.fixed_signals.push_back(result.signal_count - 1);

    validate_source_writer_conflicts(result, devices);
    validate_consumer_guardrails(result, consumer_device_names, devices);
    topological_sort_consumers(result, consumer_device_names, devices);
}

}  // namespace jit_solver_impl
)";
}

/// Generate the full build_factory.cpp content into oss.
/// Data-driven approach: per-component consume_params overloads + generic template + dispatch table.
/// Only LUT (arena allocation) and RefNode (fixed signal registration) need custom builders.
static void emit_build_factory_content(std::ostringstream& oss, const std::vector<ComponentPorts>& all_components) {
    oss << "// Auto-generated by codegen from library/*.blueprint\n";
    oss << "// DO NOT EDIT - changes will be overwritten\n\n";
    oss << "#include \"jit_solver_internal.h\"\n";
    oss << "#include \"build_components_common.h\"\n";
    oss << "#include \"components/all.h\"\n";
    oss << "\n";
    oss << "#include <algorithm>\n";
    oss << "\n";
    oss << "namespace jit_solver_impl {\n\n";

    // SchedulerRoleKind is defined in component_types.h — Consumer, Source, None.
    // No local enum needed for build_generic dispatch.

    // Per-component consume_params overloads
    oss << "// Per-component param consumers — the \"data\" in data-driven.\n";
    oss << "// Each overload is selected by the generic template via overload resolution.\n\n";
    for (const auto& comp : all_components) {
        emit_consume_params_overload(oss, comp);
    }

    // Generic template
    emit_build_generic_template(oss);

    // Special builders for non-vanilla components
    for (const auto& comp : all_components) {
        if (comp.solver_role_kind == SolverRoleKind::FixedVoltageNode) {
            emit_build_RefNode(oss, comp);
        } else if (needs_special_builder(comp)) {
            emit_build_LUT(oss, comp);
        }
    }

    // Dispatch table + main function
    emit_dispatch_table_and_main(oss, all_components);
}

