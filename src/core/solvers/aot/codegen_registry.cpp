void CodeGen::write_files(
    const std::string& out_dir,
    const std::string& source_file,
    const std::vector<ResolvedDevice>& devices,
    const std::unordered_map<std::string, uint32_t>& port_to_signal,
    uint32_t signal_count,
    const ElectricalPlanCodegen& electrical_plan_arg
) {
    ElectricalPlanCodegen electrical_plan = electrical_plan_arg;
    if (electrical_plan.islands.empty() && !devices.empty()) {
        electrical_plan = extract_electrical_plan(devices, port_to_signal);
    }

    warn_lua_script_devices(devices);

    std::string base_name = source_file;
    size_t pos = base_name.find_last_of("/\\");
    if (pos != std::string::npos) {
        base_name = base_name.substr(pos + 1);
    }
    pos = base_name.find_last_of('.');
    if (pos != std::string::npos) {
        base_name = base_name.substr(0, pos);
    }
    std::string const header_name = "generated_" + base_name + ".h";

    std::string const header_path = out_dir + "/" + header_name;
    std::string const source_name = "generated_" + base_name + ".cpp";
    std::string const source_path = out_dir + "/" + source_name;

    std::cerr << "[codegen] Writing optimized ECS-like header to: " << header_path << "\n";
    std::cerr << "[codegen] Writing optimized ECS-like source to: " << source_path << "\n";

    std::string const header = generate_header(source_file, devices, port_to_signal, signal_count, "Systems", electrical_plan);
    std::ofstream hfile(header_path);
    if (!hfile.is_open()) {
        std::cerr << "Failed to open: " << header_path << "\n";
        return;
    }
    hfile << header;
    hfile.close();

    std::string const source = generate_source(header_name, devices, port_to_signal, signal_count, "Systems", electrical_plan);
    std::ofstream sfile(source_path);
    if (!sfile.is_open()) {
        std::cerr << "Failed to open: " << source_path << "\n";
        return;
    }
    sfile << source;
    sfile.close();
}

void CodeGen::generate_component_kind(const ComponentRegistry& registry, const std::string& output_path) {
    auto all_components = build_component_metadata(registry);

    std::ostringstream oss;
    oss << "// Auto-generated by codegen from library/*.blueprint\n";
    oss << "// DO NOT EDIT - changes will be overwritten\n\n";
    oss << "#pragma once\n\n";
    oss << "#include <cstdint>\n";
    oss << "#include <optional>\n";
    oss << "#include <string_view>\n\n";

    // Enum — alphabetical order matches codegen iteration order.
    // Unknown: valid sentinel for "not resolved" (in-bounds, safe in switch).
    // _COUNT: array sizing only — never used as a value.
    oss << "/// ComponentKind — enumeration of every primitive component type.\n";
    oss << "/// Resolved once at load/elaboration time from the string classname.\n";
    oss << "/// All downstream dispatch uses this enum instead of string comparison.\n";
    oss << "///\n";
    oss << "/// Unknown — valid sentinel for \"not resolved\". In-bounds, safe in switch,\n";
    oss << "/// but has_component_metadata(Unknown) == false.\n";
    oss << "/// _COUNT — array sizing only. Never used as a value.\n";
    oss << "///\n";
    oss << "/// NOTE: This file is auto-generated. To add a new component, add a\n";
    oss << "/// .blueprint to the library and re-run update_port_registry.\n\n";
    oss << "enum class ComponentKind : uint8_t {\n";
    for (size_t i = 0; i < all_components.size(); ++i) {
        oss << "    " << all_components[i].classname << ",\n";
    }
    oss << "    Unknown,\n";
    oss << "    _COUNT\n";
    oss << "};\n\n";

    // parse_component_kind — if-chain (load-time, not hot path)
    oss << "/// Resolve a string classname to ComponentKind. Returns std::nullopt for unknown names.\n";
    oss << "inline std::optional<ComponentKind> parse_component_kind(std::string_view name) {\n";
    for (const auto& comp : all_components) {
        oss << "    if (name == \"" << comp.classname << "\") return ComponentKind::" << comp.classname << ";\n";
    }
    oss << "    return std::nullopt;\n";
    oss << "}\n\n";

    // component_kind_classname — inverse mapping (constexpr)
    oss << "/// Inverse mapping: ComponentKind → string_view classname (for diagnostics/serialization).\n";
    oss << "inline constexpr std::string_view component_kind_classname(ComponentKind kind) {\n";
    oss << "    switch (kind) {\n";
    for (const auto& comp : all_components) {
        oss << "        case ComponentKind::" << comp.classname << ": return \"" << comp.classname << "\";\n";
    }
    oss << "        case ComponentKind::Unknown: return \"Unknown\";\n";
    oss << "        case ComponentKind::_COUNT: return \"_COUNT\";\n";
    oss << "    }\n";
    oss << "    return \"Unknown\";\n";
    oss << "}\n\n";

    // Family predicates — data-driven from solver_role_kind metadata.
    // Each entry: {predicate_name, doc_string, filter}.  New families just add a row.
    struct FamilyDef {
        const char* predicate_name;
        const char* doc_string;
        SolverRoleKind role_kind;
    };
    const FamilyDef families[] = {
        {"is_knob_switch_kind", "KnobSwitch family", KNOB_SWITCH_BRANCHES_ROLE},
    };

    for (const auto& fam : families) {
        std::vector<std::string> members;
        for (const auto& comp : all_components) {
            if (comp.solver_role_kind == fam.role_kind) {
                members.push_back(comp.classname);
            }
        }
        if (members.empty()) continue;

        oss << "/// " << fam.doc_string << ": solver_role.kind == \"" << solver_role_kind_name(fam.role_kind) << "\".\n";
        oss << "inline constexpr bool " << fam.predicate_name << "(ComponentKind kind) {\n";
        if (members.size() == 1) {
            oss << "    return kind == ComponentKind::" << members[0] << ";\n";
        } else {
            oss << "    return ";
            for (size_t i = 0; i < members.size(); ++i) {
                oss << "kind == ComponentKind::" << members[i];
                if (i < members.size() - 1) {
                    oss << " ||\n           ";
                }
            }
            oss << ";\n";
        }
        oss << "}\n\n";
    }

    std::ofstream out(output_path);
    if (!out.is_open()) {
        std::cerr << "[codegen] Error: could not write to " << output_path << "\n";
        return;
    }
    out << oss.str();
    out.close();

    std::cerr << "[codegen] Generated component_kind: " << output_path << "\n";
}

void CodeGen::generate_port_registry(const ComponentRegistry& registry, const std::string& output_path) {
    auto all_components = build_component_metadata(registry);

    std::set<std::string> all_port_names;
    for (const auto& comp : all_components) {
        for (const auto& port : comp.ports) {
            all_port_names.insert(port.name);
        }
    }

    // Determine output directory from output_path
    std::string dir = output_path;
    auto slash = dir.find_last_of("/\\");
    if (slash != std::string::npos) {
        dir = dir.substr(0, slash + 1);
    } else {
        dir.clear();
    }

    // 1. Emit port_metadata.h (no all.h, no variant)
    {
        std::ostringstream oss;
        emit_port_metadata_prelude(oss, all_components);
        emit_port_metadata_arrays(oss, all_components);

        std::string const meta_path = dir + "port_metadata.h";
        std::ofstream out(meta_path);
        if (out.is_open()) {
            out << oss.str();
            out.close();
            std::cerr << "[codegen] Generated port_metadata.h: " << meta_path << "\n";
        }
    }

    // 2. Emit port_traits.h (lookup functions, trait arrays, predicates — NO all.h)
    {
        std::ostringstream oss;
        emit_port_traits_prelude(oss);
        emit_port_traits_lookups(oss, all_components, all_port_names);
        emit_port_traits_arrays(oss, all_components);

        std::string const traits_path = dir + "port_traits.h";
        std::ofstream out(traits_path);
        if (out.is_open()) {
            out << oss.str();
            out.close();
            std::cerr << "[codegen] Generated port_traits.h: " << traits_path << "\n";
        }
    }

    // 3. Emit port_queries.h (ComponentVariant + static_asserts — needs all.h)
    {
        std::ostringstream oss;
        emit_port_queries_prelude(oss);
        emit_port_queries_variant(oss, all_components);

        std::string const queries_path = dir + "port_queries.h";
        std::ofstream out(queries_path);
        if (out.is_open()) {
            out << oss.str();
            out.close();
            std::cerr << "[codegen] Generated port_queries.h: " << queries_path << "\n";
        }
    }

    // 4. Emit port_registry.h (convenience umbrella include)
    {
        std::ostringstream oss;
        oss << "// Auto-generated by codegen from library/*.blueprint\n";
        oss << "// DO NOT EDIT - changes will be overwritten\n";
        oss << "// This file includes all port-related headers for convenience.\n";
        oss << "// For minimal includes, use port_names.h, port_metadata.h, or port_traits.h directly.\n\n";
        oss << "#pragma once\n\n";
        oss << "#include \"port_metadata.h\"\n";
        oss << "#include \"port_traits.h\"\n";
        oss << "#include \"port_queries.h\"\n";

        std::ofstream out(output_path);
        if (out.is_open()) {
            out << oss.str();
            out.close();
            std::cerr << "[codegen] Generated port_registry.h: " << output_path << "\n";
        }
    }

    generate_port_names_header(output_path, all_port_names);
}

void CodeGen::generate_build_factory(const ComponentRegistry& registry, const std::string& output_path) {
    auto all_components = build_component_metadata(registry);

    std::ostringstream oss;
    emit_build_factory_content(oss, all_components);

    std::ofstream out(output_path);
    if (!out.is_open()) {
        std::cerr << "[codegen] Error: could not write to " << output_path << "\n";
        return;
    }
    out << oss.str();
    out.close();

    std::cerr << "[codegen] Generated build factory: " << output_path << "\n";
}
