/// Solver role kind constants — single source of truth for codegen predicates.
static constexpr SolverRoleKind KNOB_SWITCH_BRANCHES_ROLE = SolverRoleKind::KnobSwitchBranches;

struct PortMeta {
    std::string name;
    bp2::Direction direction = bp2::Direction::Output;
    Domain domain = Domain::Electrical;
    bool source_writer = false;
};

/// Codegen representation of a param entry from param_schema.
struct CodegenParam {
    std::string name;             ///< JSON param key (e.g. "v_nominal")
    std::string field;            ///< C++ field name override (empty = same as name)
    ParamSchemaType type;         ///< float/int/bool/string/table
    std::string default_value;    ///< From param_defaults (string form)
    std::string arena_field_offset; ///< For table type: component field receiving arena offset
    std::string arena_field_size;   ///< For table type: component field receiving entry count
};

struct ComponentPorts {
    std::string classname;
    std::vector<PortMeta> ports;
    std::vector<CodegenParam> params;
    std::optional<SolverRoleKind> solver_role_kind;  ///< nullopt if no solver_role
    SchedulerRoleKind scheduler_role_kind = SchedulerRoleKind::Consumer;
};

std::vector<ComponentPorts> build_component_metadata(const ComponentRegistry& registry) {
    std::vector<ComponentPorts> all_components;

    for (const auto& [name, spec] : registry.all_types()) {
        (void)name;
        const auto* def = as_primitive(spec);
        if (!def) {
            continue;
        }

        ComponentPorts comp;
        comp.classname = def->classname;
        comp.solver_role_kind = def->solver.solver_role.has_value()
            ? std::optional<SolverRoleKind>(def->solver.solver_role->kind) : std::nullopt;
        comp.scheduler_role_kind = def->solver.scheduler_role_kind;

        // Collect non-visual-only params sorted by name for deterministic codegen
        for (const auto& [param_name, param_spec] : def->params) {
            if (param_spec.visual_only) continue;
            CodegenParam cp;
            cp.name = param_name;
            cp.field = param_spec.field.empty() ? param_name : param_spec.field;
            cp.type = param_spec.type;
            cp.default_value = param_spec.default_value;
            cp.arena_field_offset = param_spec.arena_field_offset;
            cp.arena_field_size = param_spec.arena_field_size;
            comp.params.push_back(std::move(cp));
        }
        std::sort(comp.params.begin(), comp.params.end(),
            [](const CodegenParam& a, const CodegenParam& b) { return a.name < b.name; });

        for (const auto& [port_name, port] : def->ports) {
            PortMeta meta;
            meta.name = port_name;
            meta.direction = port.direction;
            meta.domain = port.domain;
            meta.source_writer = port.source_writer;
            comp.ports.push_back(std::move(meta));
        }
        std::sort(comp.ports.begin(), comp.ports.end(),
            [](const PortMeta& a, const PortMeta& b) { return a.name < b.name; });
        all_components.push_back(std::move(comp));
    }

    std::sort(all_components.begin(), all_components.end(),
        [](const ComponentPorts& a, const ComponentPorts& b) { return a.classname < b.classname; });

    return all_components;
}

void generate_port_names_header(const std::string& output_path, const std::set<std::string>& all_port_names) {
    std::string dir = output_path;
    auto slash = dir.find_last_of("/\\");
    if (slash != std::string::npos) {
        dir = dir.substr(0, slash + 1);
    } else {
        dir.clear();
    }
    std::string const port_names_path = dir + "port_names.h";

    std::ostringstream pn;
    pn << "// Auto-generated by codegen from library/*.blueprint\n";
    pn << "// DO NOT EDIT - changes will be overwritten\n\n";
    pn << "#pragma once\n\n";
    pn << "#include <cstdint>\n\n";
    pn << "enum class PortNames : uint32_t {\n";
    for (const auto& port_name : all_port_names) {
        pn << "    " << port_name << ",\n";
    }
    pn << "    _COUNT\n";
    pn << "};\n";

    std::ofstream pn_out(port_names_path);
    if (pn_out.is_open()) {
        pn_out << pn.str();
        pn_out.close();
    }
}

